#!/usr/bin/env python3
"""
Generate Day 4 Benchmark Mission Worlds and Occupancy Maps for ICRA 2027 Evaluation.

Generates SDF world files (.world) and ROS OccupancyGrid maps (.yaml and .pgm):
1. causal_benchmark: World layout with UNMAPPED DYNAMIC OBSTACLE TEST SCENARIO:
   - South Divider Wall 1 (y = -6.0m):
     * Doorway 1A (Left, centered at x = -1.50m): 1.25m Wide Doorway (allows CARRY pose!)
     * Doorway 1B (Right, centered at x = +1.50m): 0.85m Narrow Doorway
   - Constant 1.25m Corridor connected to Doorway 1A (from y = -6.0m to y = -3.0m, length = 3.0m)
   - Middle Room Obstacle Locations:
     * box_middle_west: (-0.61, 1.01, 0.50) -> MAPPED on 2D static map & present in 3D Gazebo
     * box_middle_east: (1.01, 3.55, 0.50) -> UNMAPPED on 2D static map (removed from map for real-time dynamic obstacle evaluation!), but PRESENT in 3D Gazebo physics simulation!
   - North Divider Wall 3 (y = +6.0m): Single 1.30m Wide Doorway into North Room
   - Room Obstacles in South and North open halls.

2. Individual focused variants (doorway_075m, two_constrictions, box_corridor).

Saves world files to both gazebo_simulation/worlds and pal_gazebo_worlds/worlds.
"""

import os
import sys

GAZEBO_SIM_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.dirname(GAZEBO_SIM_DIR)
PAL_GAZEBO_WORLDS_DIR = os.path.join(SRC_DIR, "pal_gazebo_worlds", "worlds")

WORLDS_DIRS = [
    os.path.join(GAZEBO_SIM_DIR, "worlds"),
    PAL_GAZEBO_WORLDS_DIR
]
MAPS_DIR = os.path.join(GAZEBO_SIM_DIR, "maps")

for d in WORLDS_DIRS:
    os.makedirs(d, exist_ok=True)
os.makedirs(MAPS_DIR, exist_ok=True)


def write_pgm_and_yaml(map_name: str, grid: list, resolution: float, origin_x: float, origin_y: float):
    """Save 2D occupancy grid as ASCII PGM (P2 format) and ROS map metadata YAML."""
    height = len(grid)
    width = len(grid[0])

    pgm_path = os.path.join(MAPS_DIR, f"{map_name}.pgm")
    yaml_path = os.path.join(MAPS_DIR, f"{map_name}.yaml")

    with open(pgm_path, "w") as f:
        f.write("P2\n")
        f.write(f"# Map generated by generate_mission_worlds.py for {map_name}\n")
        f.write(f"{width} {height}\n")
        f.write("255\n")
        for row in reversed(grid):
            f.write(" ".join(str(val) for val in row) + "\n")

    yaml_content = (
        f"image: {map_name}.pgm\n"
        f"mode: trinary\n"
        f"resolution: {resolution:.4f}\n"
        f"origin: [{origin_x:.4f}, {origin_y:.4f}, 0.0000]\n"
        f"negate: 0\n"
        f"occupied_thresh: 0.65\n"
        f"free_thresh: 0.25\n"
    )
    with open(yaml_path, "w") as f:
        f.write(yaml_content)

    print(f"Generated map: {yaml_path} ({width}x{height} cells, res={resolution}m/px)")


def save_world_sdf(world_name: str, world_sdf: str):
    """Save world SDF string to all registered world directories."""
    for wdir in WORLDS_DIRS:
        wpath = os.path.join(wdir, f"{world_name}.world")
        with open(wpath, "w") as f:
            f.write(world_sdf)
        print(f"Generated world: {wpath} ✓")


def create_wall_box_sdf(name: str, x: float, y: float, z: float, dx: float, dy: float, dz: float = 2.0) -> str:
    """Generate SDF string for a static wall/obstacle box model."""
    return f"""
    <model name='{name}'>
      <static>1</static>
      <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 0</pose>
      <link name='link'>
        <collision name='collision'>
          <geometry>
            <box>
              <size>{dx:.4f} {dy:.4f} {dz:.4f}</size>
            </box>
          </geometry>
        </collision>
        <visual name='visual'>
          <geometry>
            <box>
              <size>{dx:.4f} {dy:.4f} {dz:.4f}</size>
            </box>
          </geometry>
          <material>
            <script>
              <uri>file://media/materials/scripts/gazebo.material</uri>
              <name>Gazebo/Grey</name>
            </script>
          </material>
        </visual>
      </link>
    </model>"""


def wrap_sdf_world(world_name: str, models_sdf: str) -> str:
    """Wrap models in standard Gazebo ROS 2 world SDF frame."""
    return f"""<sdf version='1.7'>
  <world name='{world_name}'>
    <plugin name="gazebo_ros_state" filename="libgazebo_ros_state.so">
      <ros>
        <namespace>/gazebo</namespace>
      </ros>
      <update_rate>50.0</update_rate>
    </plugin>
    <plugin name="collision_monitor" filename="libcollision_monitor.so">
      <ros>
        <namespace>/gazebo</namespace>
      </ros>
      <robot_name>tiago</robot_name>
      <ignore_models>ground_plane</ignore_models>
      <force_threshold>1.0</force_threshold>
      <publish_rate>50</publish_rate>
    </plugin>
    
    <!-- Light & Ground -->
    <include>
      <uri>model://sun</uri>
    </include>
    <include>
      <uri>model://ground_plane</uri>
    </include>
{models_sdf}
  </world>
</sdf>
"""



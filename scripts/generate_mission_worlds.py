# UNIFIED BENCHMARK WORLD: causal_benchmark (UNMAPPED DYNAMIC OBSTACLE AT x=1.01, y=3.55)
# ==============================================================================
def generate_unified_causal_benchmark():
    world_name = "causal_benchmark"
    res = 0.05
    x_min, x_max = -5.0, 5.0    # 10m total width
    y_min, y_max = -12.0, 12.0  # 24m total length
    wall_t = 0.20

    width_px = int(round((x_max - x_min) / res))
    height_px = int(round((y_max - y_min) / res))

    grid = [[254 for _ in range(width_px)] for _ in range(height_px)]

    # Obstacles burned into 2D Static Map (mapped_obstacles)
    # box_middle_west (-0.61, 1.01) IS MAPPED
    # box_middle_east (1.01, 3.55) IS UNMAPPED (omitted from static map so global planner is unaware!)
    mapped_obstacles = [
        # South Left Room: Table against outer wall
        (-3.80, -9.0, 1.2, 0.8, "table_south_west"),
        # South Right Room: Table at x = +3.8m, y = -9.0m
        (3.80, -9.0, 1.2, 0.8, "table_south_east"),
        # Middle Room Obstacle 1 (MAPPED): box_middle_west at x = -0.61m, y = 1.01m
        (-0.61, 1.01, 0.80, 0.60, "box_middle_west"),
        # North Left Room: Cabinet against outer wall
        (-3.80, 9.5, 1.2, 0.8, "cabinet_north_west"),
        # North Right Room: Cabinet at x = +3.8m, y = +9.5m
        (3.80, 9.5, 1.2, 0.8, "cabinet_north_east"),
    ]

    # Obstacles present in 3D Gazebo Physics Simulation (sdf_obstacles)
    # Includes BOTH box_middle_west (mapped) AND box_middle_east (unmapped dynamic obstacle!)
    sdf_obstacles = [
        (-3.80, -9.0, 0.5, 1.2, 0.8, 1.0, "table_south_west"),
        (3.80, -9.0, 0.5, 1.2, 0.8, 1.0, "table_south_east"),
        # MAPPED OBSTACLE: box_middle_west at (-0.61, 1.01, 0.5)
        (-0.61, 1.01, 0.5, 0.80, 0.60, 1.0, "box_middle_west"),
        # UNMAPPED DYNAMIC OBSTACLE: box_middle_east at (1.01, 3.55, 0.5)
        (1.01, 3.55, 0.5, 0.80, 0.60, 1.0, "box_middle_east"),
        (-3.80, 9.5, 0.5, 1.2, 0.8, 1.0, "cabinet_north_west"),
        (3.80, 9.5, 0.5, 1.2, 0.8, 1.0, "cabinet_north_east"),
    ]

    for r in range(height_px):
        for c in range(width_px):
            x_m = x_min + c * res
            y_m = y_min + r * res

            # Outer boundary
            if x_m <= x_min + wall_t or x_m >= x_max - wall_t or y_m <= y_min + wall_t or y_m >= y_max - wall_t:
                grid[r][c] = 0

            # Divider Wall 1 at y = -6.0m:
            # Doorway 1A (Left, centered at x=-1.50m, width=1.25m): free in x in [-2.125, -0.875]
            # Doorway 1B (Right, centered at x=+1.50m, width=0.85m): free in x in [1.075, 1.925]
            elif abs(y_m - (-6.0)) <= wall_t / 2.0:
                is_door_1a = (-2.125 <= x_m <= -0.875)
                is_door_1b = (1.075 <= x_m <= 1.925)
                if not (is_door_1a or is_door_1b):
                    grid[r][c] = 0

            # Constant-Width 1.25m Corridor connected to Doorway 1A (y in [-6.0m, -3.0m], length = 3.0m):
            elif (-6.0 < y_m <= -3.0) and ((-2.325 <= x_m <= -2.125) or (-0.875 <= x_m <= -0.675)):
                grid[r][c] = 0

            # Divider Wall 3 at y = +6.0m: Single 1.30m Wide Doorway (centered at x=0.0m, free in x in [-0.65, +0.65])
            elif abs(y_m - 6.0) <= wall_t / 2.0:
                if not (-0.65 <= x_m <= 0.65):
                    grid[r][c] = 0

            # Room Obstacles (Static Map)
            else:
                for ox, oy, odx, ody, _ in mapped_obstacles:
                    if (ox - odx / 2.0 <= x_m <= ox + odx / 2.0) and (oy - ody / 2.0 <= y_m <= oy + ody / 2.0):
                        grid[r][c] = 0
                        break

    write_pgm_and_yaml(world_name, grid, res, x_min, y_min)

    # SDF Models (3D Gazebo Simulation)
    w_models = []
    # Outer walls
    w_models.append(create_wall_box_sdf("wall_south", 0.0, y_min, 1.0, x_max - x_min, wall_t))
    w_models.append(create_wall_box_sdf("wall_north", 0.0, y_max, 1.0, x_max - x_min, wall_t))
    w_models.append(create_wall_box_sdf("wall_west", x_min, 0.0, 1.0, wall_t, y_max - y_min))
    w_models.append(create_wall_box_sdf("wall_east", x_max, 0.0, 1.0, wall_t, y_max - y_min))

    # Divider Wall 1 at y = -6.0m (Dual Doorways: 1.25m Left Doorway 1A, 0.85m Right Doorway 1B)
    w_models.append(create_wall_box_sdf("div1_seg1", (x_min - 2.125) / 2.0, -6.0, 1.0, abs(-2.125 - x_min), wall_t))
    w_models.append(create_wall_box_sdf("div1_seg2", (-0.875 + 1.075) / 2.0, -6.0, 1.0, (1.075 - (-0.875)), wall_t))
    w_models.append(create_wall_box_sdf("div1_seg3", (1.925 + x_max) / 2.0, -6.0, 1.0, (x_max - 1.925), wall_t))

    # Constant-Width 1.25m Corridor Walls connected to Doorway 1A (y in [-6.0m, -3.0m], length = 3.0m)
    w_models.append(create_wall_box_sdf("corridor_west_wall", -2.225, -4.5, 1.0, wall_t, 3.0))
    w_models.append(create_wall_box_sdf("corridor_east_wall", -0.775, -4.5, 1.0, wall_t, 3.0))

    # Divider Wall 3 at y = +6.0m (Single 1.30m Wide Doorway at x=0.0m)
    seg3_w = (x_max - x_min) / 2.0 - 1.30 / 2.0
    w_models.append(create_wall_box_sdf("div3_west", x_min + seg3_w / 2.0, 6.0, 1.0, seg3_w, wall_t))
    w_models.append(create_wall_box_sdf("div3_east", x_max - seg3_w / 2.0, 6.0, 1.0, seg3_w, wall_t))

    # Add Room Obstacles to SDF (Includes unmapped dynamic obstacle box_middle_east at x=1.01, y=3.55!)
    for ox, oy, oz, odx, ody, odz, name in sdf_obstacles:
        w_models.append(create_wall_box_sdf(name, ox, oy, oz, odx, ody, odz))

    world_sdf = wrap_sdf_world(world_name, "\n".join(w_models))
    save_world_sdf(world_name, world_sdf)


# Focused Variant
def generate_variant_1_doorway():
    world_name = "doorway_075m"
    res = 0.05
    x_min, x_max = -4.0, 4.0
    y_min, y_max = -8.0, 8.0
    door_width = 0.85
    wall_t = 0.20

    width_px = int(round((x_max - x_min) / res))
    height_px = int(round((y_max - y_min) / res))

    grid = [[254 for _ in range(width_px)] for _ in range(height_px)]
    center_x_px = int(round((-x_min) / res))
    door_half_px = int(round((door_width / 2.0) / res))

    for r in range(height_px):
        for c in range(width_px):
            x_m = x_min + c * res
            y_m = y_min + r * res
            if x_m <= x_min + wall_t or x_m >= x_max - wall_t or y_m <= y_min + wall_t or y_m >= y_max - wall_t:
                grid[r][c] = 0
            elif abs(y_m) <= wall_t / 2.0:
                if not (center_x_px - door_half_px <= c <= center_x_px + door_half_px):
                    grid[r][c] = 0

    write_pgm_and_yaml(world_name, grid, res, x_min, y_min)

    w_models = []
    w_models.append(create_wall_box_sdf("wall_south", 0.0, y_min, 1.0, x_max - x_min, wall_t))
    w_models.append(create_wall_box_sdf("wall_north", 0.0, y_max, 1.0, x_max - x_min, wall_t))
    w_models.append(create_wall_box_sdf("wall_west", x_min, 0.0, 1.0, wall_t, y_max - y_min))
    w_models.append(create_wall_box_sdf("wall_east", x_max, 0.0, 1.0, wall_t, y_max - y_min))

    left_seg_width = (x_max - x_min) / 2.0 - door_width / 2.0
    w_models.append(create_wall_box_sdf("divider_west", x_min + left_seg_width / 2.0, 0.0, 1.0, left_seg_width, wall_t))
    w_models.append(create_wall_box_sdf("divider_east", x_max - left_seg_width / 2.0, 0.0, 1.0, left_seg_width, wall_t))

    world_sdf = wrap_sdf_world(world_name, "\n".join(w_models))
    save_world_sdf(world_name, world_sdf)


def main():
    print("=== ICRA 2027 DAY 4: GENERATING BENCHMARK WORLD WITH UNMAPPED DYNAMIC OBSTACLE AT (1.01, 3.55) ===")
    generate_unified_causal_benchmark()
    generate_variant_1_doorway()
    print("All benchmark mission worlds & map files generated successfully! ✓\n")


if __name__ == "__main__":
    main()
